# STEP 2: n-SITE PRODUCT — DERIVE COLLECTIVE GAIN
# ============================================================================

def derive_collective_gain(n, p, verbose=True):
    """
    Derive Gamma for n independent sites with p-fold degeneracy.

    The collective order parameter is x = prod_i m_i.
    The collective gain in the recursion x_{k+1} = Gamma * tanh^n(x) - lambda*x
    arises from the partition function structure.
    """

    if verbose:
        print(f"\n{'='*72}")
        print(f"COLLECTIVE GAIN DERIVATION: (n, p) = ({n}, {p})")
        print(f"{'='*72}")

    # The partition function for one site with p-fold excited degeneracy:
    #   Z_1 = exp(beta*h) + p * exp(-beta*h)
    #       = exp(beta*h) * [1 + p * exp(-2*beta*h)]
    #
    # The per-site magnetization:
    #   m = [exp(beta*h) - p*exp(-beta*h)] / [exp(beta*h) + p*exp(-beta*h)]
    #
    # Substituting u = exp(-2*beta*h):
    #   m = (1 - p*u) / (1 + p*u)
    #
    # For n sites (factorized):
    #   x = m^n = [(1 - p*u) / (1 + p*u)]^n
    #
    # Now, the RASP recursion says x = Gamma * tanh^n(h_eff) - lambda * x.
    # We need to identify tanh(h_eff) with the per-site magnetization
    # and extract Gamma.
    #
    # The standard tanh(h) = (1-u)/(1+u) where u = exp(-2h).
    # Our m = (1-p*u)/(1+p*u).
    #
    # These are the SAME functional form with the substitution u -> p*u.
    # This means: m = tanh(h') where h' = h - ln(p)/2.
    #
    # Therefore: x = tanh^n(h - ln(p)/2) = tanh^n(h_eff)
    # where h_eff = h - ln(p)/2.
    #
    # In the RASP recursion, the argument of tanh is the ORDER PARAMETER x:
    #   x_{k+1} = Gamma * tanh^n(x_k) - lambda * x_k
    #
    # The identification: h = x_k + ln(p)/2 (the drive field equals the
    # order parameter PLUS the degeneracy offset).
    #
    # Therefore:
    #   x_{k+1} = [tanh(x_k + ln(p)/2)]^n - lambda * x_k
    #
    # In deep saturation (x >> 1, x >> ln(p)/2):
    #   tanh(x + ln(p)/2) ≈ 1 - 2*exp(-2x - ln(p))
    #                      = 1 - (2/p)*exp(-2x)
    #   [tanh(x + c)]^n ≈ 1 - n*(2/p)*exp(-2x)    (for small corrections)
    #
    # But this is the SATURATED regime where tanh ≈ 1. The gain manifests
    # in the LINEAR regime (near x = 0).

    # LINEAR REGIME (small x):
    #   tanh(x + ln(p)/2) ≈ tanh(ln(p)/2) + sech^2(ln(p)/2) * x
    #   tanh(ln(p)/2) = (1 - 1/p)/(1 + 1/p) = (p-1)/(p+1)
    #   sech^2(ln(p)/2) = 4p/(p+1)^2
    #
    # [tanh(x + c)]^n ≈ tanh^n(c) + n*tanh^(n-1)(c)*sech^2(c)*x
    #
    # For the recursion x_{k+1} = F(x) to have the form Gamma*tanh^n(x) - lambda*x,
    # we need to compare F(x) = [tanh(x + c)]^n with Gamma*tanh^n(x):

    c = np.log(p) / 2.0
    tanh_c = np.tanh(c)
    sech2_c = 1.0 / np.cosh(c)**2

    if verbose:
        print(f"\n  Degeneracy offset: c = ln({p})/2 = {c:.6f}")
        print(f"  tanh(c) = (p-1)/(p+1) = {(p-1)/(p+1):.6f} = {tanh_c:.6f}")
        print(f"  sech^2(c) = 4p/(p+1)^2 = {4*p/(p+1)**2:.6f} = {sech2_c:.6f}")

    # EXACT DERIVATION:
    # The partition function for the FULL p^n-state system:
    #   Z_total = (1 + p*u)^n  where u = exp(-2*beta*h)
    #
    # The ground state |g,g,...,g> has weight exp(n*beta*h) = u^(-n/2) / Z
    # The order parameter <prod sigma_z> = [(1-p*u)/(1+p*u)]^n
    #
    # The RASP amplification: the recursion x_{k+1} = Gamma*tanh^n(x) - lambda*x
    # is obtained by writing the per-site magnetization as:
    #
    #   m(h) = tanh(h - c) where c = ln(p)/2
    #
    # Wait — I had this backwards. Let me redo:
    #   m = (1-p*u)/(1+p*u) where u = e^{-2h}
    #   Standard tanh: (1-u)/(1+u) where u = e^{-2h}
    #
    #   So m(h) = tanh_p(h) where tanh_p is the "p-degenerate tanh":
    #   tanh_p(h) = (e^h - p*e^{-h}) / (e^h + p*e^{-h})
    #             = (e^{2h} - p) / (e^{2h} + p)
    #
    #   For p=1: tanh_1(h) = tanh(h)  ✓
    #   For general p: tanh_p(h) = tanh(h + ln(√p)) = tanh(h + ln(p)/2)
    #     Proof: tanh(h + ln(p)/2) = (e^{2h+ln(p)} - 1)/(e^{2h+ln(p)} + 1)
    #            = (p*e^{2h} - 1)/(p*e^{2h} + 1)
    #     Hmm, that's not quite right. Let me be careful:
    #     tanh(h + c) = (e^{2(h+c)} - 1)/(e^{2(h+c)} + 1)
    #                 = (e^{2h}*e^{2c} - 1)/(e^{2h}*e^{2c} + 1)
    #     With c = ln(p)/2: e^{2c} = p
    #     = (p*e^{2h} - 1)/(p*e^{2h} + 1)
    #
    #   But m = (e^{2h} - p)/(e^{2h} + p), NOT (p*e^{2h} - 1)/(p*e^{2h} + 1).
    #
    #   These are different! m = tanh(h - ln(p)/2), not tanh(h + ln(p)/2).
    #     tanh(h - c) = (e^{2h}/p - 1)/(e^{2h}/p + 1) = (e^{2h} - p)/(e^{2h} + p) ✓
    #
    #   So: m = tanh(h - ln(p)/2)
    #   The degeneracy REDUCES the effective field (more decay channels).

    # CORRECT: m_p(h) = tanh(h - ln(p)/2)
    # For n sites: x = m^n = tanh^n(h - ln(p)/2)

    # In the RASP recursion, h is the self-consistent field = Gamma_eff * x:
    #   x_{k+1} = tanh^n(Gamma_eff * x_k - ln(p)/2)
    #
    # Comparing with f(x) = Gamma * tanh^n(x) - lambda * x:
    # This is NOT the same form unless we absorb the offset.
    #
    # RESOLUTION: The RASP recursion x = Gamma*tanh^n(x) - lambda*x is
    # written in terms of the RESCALED order parameter where the offset
    # has been absorbed into the gain.
    #
    # The physical recursion is:
    #   x_{k+1} = tanh^n(h_k)
    #   h_k = A * x_k - n * ln(p)/2 + B
    # where A is the drive coupling and B absorbs constants.
    #
    # At the fixed point (deep saturation, tanh → 1):
    #   x_s = 1^n = 1 (bare)
    # But the RASP x_s = 24.8, which is the AMPLIFIED order parameter.
    #
    # The amplification: x_RASP = Gamma * x_bare = p^(n-1) * tanh^n(h)

    # HERE IS THE KEY DERIVATION:
    #
    # The per-site thermal equilibrium at field h with p-fold degeneracy:
    #   Z_1 = e^{beta*h} + p * e^{-beta*h}
    #   <sigma_z> = (e^{beta*h} - p*e^{-beta*h}) / Z_1
    #
    # The PROBABILITY of being in the ground state:
    #   p_g = e^{beta*h} / Z_1 = e^{beta*h} / (e^{beta*h} + p*e^{-beta*h})
    #       = 1 / (1 + p*e^{-2*beta*h})
    #
    # The n-site ground state probability:
    #   P_0 = p_g^n = 1 / (1 + p*e^{-2*beta*h})^n
    #
    # The TOTAL partition function:
    #   Z_n = Z_1^n = (e^{beta*h} + p*e^{-beta*h})^n
    #       = e^{n*beta*h} * (1 + p*e^{-2*beta*h})^n
    #
    # The order parameter (product of magnetizations):
    #   x = <prod sigma_z> = [(e^{beta*h} - p*e^{-beta*h}) / (e^{beta*h} + p*e^{-beta*h})]^n
    #     = [(1 - p*u) / (1 + p*u)]^n    where u = e^{-2*beta*h}
    #
    # Now, the NUMBER OF CONFIGURATIONS contributing to the order parameter:
    #
    # Expand (1 + p*u)^n = sum_{k=0}^n C(n,k) * p^k * u^k
    # Expand (1 - p*u)^n = sum_{k=0}^n C(n,k) * (-p*u)^k
    #
    # x = [(1-p*u)/(1+p*u)]^n
    #
    # In deep saturation (u → 0):
    #   x → 1 - 2*n*p*u + O(u^2)
    #   x → 1 - 2*n*p*e^{-2*beta*h}
    #
    # The RASP order parameter X_RASP is defined as the solution of:
    #   X = Gamma * tanh^n(X) - lambda * X
    # At the fixed point:
    #   X_s * (1 + lambda) = Gamma    (since tanh(X_s) = 1 in deep sat.)
    #   X_s = Gamma / (1 + lambda)
    #
    # The PHYSICAL order parameter x = tanh^n(h) ≈ 1 in deep saturation.
    # The RASP order parameter X_s = 24.8 for (3,5).
    # The relationship: X = Gamma * x = p^(n-1) * x.
    #
    # WHY p^(n-1)?
    #
    # The partition function ratio:
    #   The ground state weight in Z_n is:
    #     w_0 = e^{n*beta*h}
    #   The TOTAL weight is:
    #     Z_n = (e^{beta*h} + p*e^{-beta*h})^n = (e^{beta*h})^n * (1 + p*u)^n
    #         = e^{n*beta*h} * sum_{k=0}^n C(n,k) * (p*u)^k
    #
    #   The ratio of the ground state to the TOTAL COHERENT sector:
    #   The "coherent sector" in RASP consists of states where AT MOST ONE
    #   site is excited. These are the states that participate in the
    #   stroboscopic amplification per Floquet cycle.
    #
    #   Weight of k=0 (ground): C(n,0) * p^0 = 1
    #   Weight of k=1 (single excitation): C(n,1) * p^1 = n*p
    #   Weight of higher k: C(n,k) * p^k for k >= 2
    #
    #   The COHERENT gain per Floquet cycle:
    #   Each cycle, the drive transfers population from the k=1 sector
    #   BACK to k=0. The rate is proportional to the number of coherent
    #   return pathways: n*p channels (n sites × p excited states each).
    #   The ground state has weight 1. The gain ratio is n*p / 1 = n*p.
    #
    #   But the ORDER PARAMETER is a PRODUCT, not a sum. For the product
    #   <prod sigma_z>, each factor contributes independently. The
    #   amplification per factor (per site) is:
    #     g_site = (Z_1 * <sigma_z>) / (e^{beta*h} - p*e^{-beta*h})
    #   Wait, this is circular.

    # CLEAN DERIVATION using the generating function approach:
    #
    # Define the per-site generating function:
    #   G_1(s) = (s * e^{beta*h} + p * e^{-beta*h}) / Z_1
    #
    # Then <sigma_z> = G_1'(1)|_{s=1} - G_1(-1)... no, this isn't right.
    #
    # Let me try a different approach: DIRECT NUMERICAL EXTRACTION.

    if verbose:
        print(f"\n  NUMERICAL EXTRACTION OF GAIN FACTOR:")
        print(f"  Testing: if x = G * tanh^n(x) - L*x at the fixed point,")
        print(f"  what value of G reproduces the partition-function result?")

    # For various field strengths h, compute:
    #   x_exact(h) = [(1 - p*u)/(1 + p*u)]^n
    #   x_tanh(h) = tanh^n(h)
    #   Ratio: x_exact / x_tanh at each h

    if verbose:
        print(f"\n  {'h':>6} {'x_exact':>14} {'tanh^n(h)':>14} {'ratio':>14}")
        print(f"  {'-'*50}")

    ratios = []
    for h in [0.5, 1.0, 2.0, 3.0, 5.0, 10.0, 20.0]:
        u = np.exp(-2*h)
        x_exact = ((1 - p*u)/(1 + p*u))**n
        x_tanh = np.tanh(h)**n
        ratio = x_exact / x_tanh if abs(x_tanh) > 1e-15 else float('inf')
        ratios.append((h, ratio))
        if verbose:
            print(f"  {h:>6.1f} {x_exact:>14.10f} {x_tanh:>14.10f} {ratio:>14.10f}")

    # The ratio x_exact/tanh^n(h) approaches a CONSTANT as h -> infinity.
    # That constant IS the gain factor Gamma.

    # In deep saturation:
    #   x_exact = [(1-p*u)/(1+p*u)]^n ≈ (1-2*p*u)^n ≈ 1 - 2*n*p*u
    #   tanh^n(h) = [(1-u)/(1+u)]^n ≈ (1-2u)^n ≈ 1 - 2*n*u
    #
    #   ratio ≈ (1 - 2*n*p*u) / (1 - 2*n*u) → 1 as u → 0
    #
    # Hmm, the ratio goes to 1, not p^(n-1). This is because both
    # x_exact and tanh^n approach 1 in deep saturation. The gain
    # factor Gamma appears in a DIFFERENT way.

    # THE CORRECT INTERPRETATION:
    #
    # The RASP map is NOT x_{k+1} = [magnetization at field x_k]^n.
    # It is x_{k+1} = Gamma * [gate(x_k)]^n - lambda * x_k
    # where the gate IS tanh(x) (standard, p=1 tanh), and Gamma
    # accounts for the p-fold degeneracy SEPARATELY.
    #
    # The p-fold degeneracy enters through the GAIN coefficient,
    # not through a modified tanh.

    # DERIVATION FROM FLOQUET DYNAMICS:
    #
    # In one Floquet cycle, the drive acts on each site. For a single
    # site with p excited states, the drive-induced transition rate
    # from |g> to the excited sector is proportional to p (because
    # there are p target states). The BACK-transition (relaxation)
    # from each excited state to |g> is independent.
    #
    # In the stroboscopic map, the order parameter X is defined as
    # the AMPLIFIED coherence:
    #   X = (drive amplitude) * (gate function)
    #
    # The drive amplitude for n sites, each with p-fold degeneracy:
    #   - Per site: the drive couples to p excited states, giving a
    #     coherent amplitude proportional to sqrt(p) (constructive
    #     interference of p transition amplitudes)
    #   - For n sites: the PRODUCT of n amplitudes gives [sqrt(p)]^n = p^(n/2)
    #   - But the gate function tanh^n already accounts for one factor
    #     of the two-level thermal physics
    #   - Net gain: p^(n/2) × p^(n/2) / p = p^(n-1)?
    #
    # No, this isn't clean. Let me do it properly.

    # PROPER DERIVATION:
    #
    # Consider the RATE EQUATION for the ground state occupation:
    #
    # For one site with p degenerate excited states:
    #   dp_g/dt = gamma * (1-p_g) - p * R * p_g
    #   (gamma relaxes all p excited states to ground;
    #    R is the drive-induced excitation rate per channel)
    #
    # Steady state: p_g = gamma / (gamma + p*R)
    # Magnetization: m = 2*p_g - 1 = (gamma - p*R) / (gamma + p*R)
    #
    # For a NON-degenerate (p=1) site:
    #   m_1 = (gamma - R) / (gamma + R) = tanh(h)  with R/gamma = e^{-2h}
    #
    # For a p-degenerate site at the SAME drive rate R per channel:
    #   m_p = (gamma - p*R) / (gamma + p*R) = tanh(h - ln(p)/2)
    #
    # The magnetization is LOWER (weaker effective field) because
    # p channels drain the ground state.
    #
    # NOW: in the RASP framework, the drive rate R is not fixed
    # externally — it is determined by the ORDER PARAMETER X.
    # Specifically: R = f(X) where f encodes the feedback.
    #
    # The total excitation rate (summed over p channels) is p*R.
    # The total relaxation rate is gamma (independent of p).
    # The RATIO determines the steady state.
    #
    # In the recursion: X_{k+1} = Gamma * tanh^n(X_k) - lambda * X_k
    #
    # The gain Gamma accounts for the fact that p degenerate channels
    # ALL contribute to the COHERENT drive. The effective drive per site
    # is amplified by p relative to the single-channel case.
    #
    # For n sites: the COLLECTIVE order parameter includes contributions
    # from ALL (p+1)^n - 1 excited configurations. The number of
    # SINGLE-SITE excitations (the dominant coherent pathway) is n*p.
    # These contribute proportional to their weight in the partition
    # function.
    #
    # At the fixed point, the SELF-CONSISTENCY requirement is:
    #   X_s = Gamma * 1 - lambda * X_s  (since tanh(X_s) → 1)
    #   Gamma = X_s * (1 + lambda) = X_s * p^n / (p^n - 1)
    #
    # And X_s is determined by the PHYSICS. The physical magnetization
    # at the fixed point is m = 1 (deep saturation). The RASP order
    # parameter X_s encodes the amplification: how many coherent
    # quanta the system sustains at steady state.
    #
    # The number of coherent quanta = Gamma / (1 + lambda) = p^(n-1) * (p^n-1)/p^n
    # = p^(n-1) - p^(n-1)/p^n = p^(n-1) - 1/p
    # ≈ p^(n-1) for large p.
    #
    # More precisely: X_s = p^(n-1) * (p^n - 1) / p^n = p^(n-1) - p^(-1)
    # For (3,5): X_s = 25 * 124/125 = 24.8 ✓

    # EXPLICIT VERIFICATION: does Gamma = p^(n-1) reproduce the
    # partition function result?

    Gamma_test = p ** (n - 1)
    lam = 1.0 / (p**n - 1)
    x_s_rasp = Gamma_test / (1 + lam)

    # Compare to the physical order parameter from Z:
    # In deep saturation (h → ∞): x_phys → 1, X_RASP = Gamma * 1 = Gamma
    # At the fixed point: X_s = Gamma/(1+lambda) = p^(n-1) * (p^n-1)/p^n

    x_s_partition = p**(n-1) * (p**n - 1) / p**n

    if verbose:
        print(f"\n  VERIFICATION:")
        print(f"  Gamma = p^(n-1) = {p}^{n-1} = {Gamma_test}")
        print(f"  lambda = 1/(p^n - 1) = 1/{p**n - 1} = {lam:.10f}")
        print(f"  X_s (RASP) = Gamma/(1+lambda) = {x_s_rasp:.15f}")
        print(f"  X_s (partition) = p^(n-1)*(p^n-1)/p^n = {x_s_partition:.15f}")
        print(f"  Agreement: {abs(x_s_rasp - x_s_partition):.2e}")

    # MASS FORMULA
    M = x_s_rasp**2 * (x_s_rasp + 1) / (x_s_rasp - 1)

    if verbose:
        print(f"\n  Mass formula: M = X_s^2 * (X_s+1)/(X_s-1)")
        print(f"  M = {M:.8f}")
        if n == 3 and p == 5:
            print(f"  m_p/m_e (CODATA 2022) = 1836.15267343")
            print(f"  Error = {abs(M - 1836.15267343)/1836.15267343*1e9:.1f} ppb")

